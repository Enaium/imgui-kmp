#!/usr/bin/env python3
"""Generates the wasm shim + export list for the ImGui C API.

Emscripten/JS cannot pass structs by value across the wasm boundary, and the
`imgui_c.h` API uses `imgui_vec2`/`imgui_vec4` by value in ~85 places plus a
couple of function-pointer parameters. This script parses the header and emits:

  * `imgui_kmp_shim.cpp`   - C wrappers that flatten those structs into scalars
                            (returns become out-parameters) and replace the
                            clipboard function-pointer setters with a static
                            buffer the JS/Kotlin side can fill;
  * `imgui_kmp_exports.js` - the `-sEXPORTED_FUNCTIONS` list as an ES module,
                            used by `imgui_kmp_glue.js` to publish every
                            function as a global for Kotlin/Wasm;

Every function that needs no wrapper is exported under its own name.
"""

import re
import sys
from pathlib import Path

HEADERS = [
    Path("jni/c_api/imgui_c.h"),
    Path("jni/c_api/implot_c.h"),
    Path("jni/c_api/markdown_c.h"),
    # Extensions ported to wasm: their raw functions must be exported (the
    # bridge calls them directly) even though none needs shim wrappers.
    Path("jni/c_api/implot3d_c.h"),
    Path("jni/c_api/node_editor_c.h"),
    Path("jni/c_api/memory_editor_c.h"),
    Path("jni/c_api/multi_context_compositor_c.h"),
]

# Structs that cross the boundary by value, with their scalar fields. Parsed
# from the header's typedefs; `imgui_draw_vert` is only ever used through a
# pointer, so it is not flattened.
VALUE_STRUCTS_FALLBACK = {
    "imgui_vec2": ["x", "y"],
    "imgui_vec4": ["x", "y", "z", "w"],
}

# Value structs are not passed by value anywhere else; pointers to them are
# ordinary 32-bit wasm pointers.
FUNC_PTR_TYPEDEFS = {"imgui_clipboard_set_fn", "imgui_clipboard_get_fn"}


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def parse_value_structs(text: str) -> dict:
    structs = dict(VALUE_STRUCTS_FALLBACK)
    for m in re.finditer(
        r"typedef\s+struct\s+(\w+)\s*\{([^}]*)\}\s*\1\s*;", text, re.S
    ):
        name, body = m.group(1), m.group(2)
        fields = []
        scalar = True
        for decl in body.split(";"):
            decl = decl.strip()
            if not decl:
                continue
            fm = re.match(r"(?:const\s+)?(float|double|int|unsigned int|bool)\s+([\w\s,]+)$", decl)
            if not fm:
                scalar = False
                break
            fields.extend(f.strip() for f in fm.group(2).split(","))
        if fields and scalar:
            structs[name] = fields
    return structs


def parse_functions(text: str):
    # Split into individual declarations first so commas inside parentheses do
    # not break the parameter split.
    pattern = re.compile(
        r"^[ \t]*([A-Za-z_][\w \t\*]*?)\s+([A-Za-z_]\w*)\s*\(([^;{]*?)\)\s*;",
        re.M | re.S,
    )
    for m in pattern.finditer(text):
        ret = " ".join(m.group(1).split())
        name = m.group(2)
        params = m.group(3)
        if name.startswith("typedef") or ret.startswith("typedef"):
            continue
        yield ret, name, params


def split_params(params: str):
    params = params.strip()
    if not params or params == "void":
        return []
    out, depth, cur = [], 0, ""
    for ch in params:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def param_type(decl: str) -> tuple:
    """Returns (type, name) without array suffixes."""
    decl = decl.strip()
    m = re.match(r"(.*?)\s*\b([A-Za-z_]\w*)\s*$", decl, re.S)
    if not m:
        return decl, ""
    return " ".join(m.group(1).split()), m.group(2)


def is_func_ptr_param(p_type: str) -> bool:
    return "(*" in p_type or p_type.strip() in FUNC_PTR_TYPEDEFS


def main() -> int:
    root = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(".")
    out_dir = Path(sys.argv[2]) if len(sys.argv) > 2 else root / "build/wasm"
    out_dir.mkdir(parents=True, exist_ok=True)

    text = strip_comments(
        "\n".join((root / h).read_text() for h in HEADERS)
    )
    structs = parse_value_structs(text)
    functions = list(parse_functions(text))

    shim = [
        "/* Generated by imgui-kmp/wasm/gen_wasm_shim.py - do not edit. */",
        "#include <stdint.h>",
        "#include <string.h>",
        *[f'#include "{h.name}"' for h in HEADERS],
        '#include "imgui_kmp_manual.h"',
        '#include "imgui_kmp_structs.h"',
        '#include "imgui_kmp_markdown.h"',
        "",
        'extern "C" {',
        "",
        "/* Clipboard: JS cannot hand C function pointers across the boundary, so",
        " * the shim installs callbacks backed by a static buffer instead. */",
        "static char imgui_kmp_clipboard[65536];",
        "static void imgui_kmp_clipboard_set(const char* text) {",
        "    if (!text) { imgui_kmp_clipboard[0] = 0; return; }",
        "    strncpy(imgui_kmp_clipboard, text, sizeof(imgui_kmp_clipboard) - 1);",
        "    imgui_kmp_clipboard[sizeof(imgui_kmp_clipboard) - 1] = 0;",
        "}",
        "static const char* imgui_kmp_clipboard_get(void) { return imgui_kmp_clipboard; }",
        "void imgui_kmp_install_clipboard(void) {",
        "    imgui_set_clipboard_callbacks(imgui_kmp_clipboard_set, imgui_kmp_clipboard_get);",
        "}",
        "const char* imgui_kmp_clipboard_read(void) { return imgui_kmp_clipboard; }",
        "void imgui_kmp_clipboard_write(const char* text) { imgui_kmp_clipboard_set(text); }",
        "",
    ]

    entries_file = root / "imgui-kmp/wasm/implot3d_points.json"
    entries = __import__("json").loads(entries_file.read_text()) if entries_file.is_file() else []

    exports = [
        "imgui_kmp_install_clipboard",
        "imgui_kmp_clipboard_read",
        "imgui_kmp_clipboard_write",
        "imgui_kmp_implot3d_getStyle",
        "imgui_kmp_implot3d_setStyle",
        "imgui_kmp_i3d_style_colors",
        "imgui_kmp_md_install",
        "imgui_kmp_md_uninstall",
        "imgui_kmp_md_drain",
        "imgui_kmp_md_event_total",
        "imgui_kmp_md_event_kind",
        "imgui_kmp_md_event_config",
        "imgui_kmp_md_event_is_image",
        "imgui_kmp_md_event_text",
        "imgui_kmp_md_event_link",
        "imgui_kmp_md_event_icon",
        "imgui_kmp_md_set_image",
    ]
    exports.extend("imgui_kmp_i3d_" + e["jvm"] for e in entries)
    wrapped = 0

    for ret, name, params in functions:
        pdecls = split_params(params)
        parsed = [param_type(p) for p in pdecls]
        if any(is_func_ptr_param(t) for t, _ in parsed):
            # Only the clipboard setters use function pointers; replaced above.
            continue

        ret_struct = ret in structs
        struct_params = [(i, t, n) for i, (t, n) in enumerate(parsed) if t in structs]
        # uint64 texture ids/params become uint32 on wasm (WebGL ids are 32-bit).
        needs_wrapper = ret_struct or struct_params or ret == "uint64_t" or any(
            t == "uint64_t" for t, _ in parsed
        )
        if not needs_wrapper:
            exports.append(name)
            continue

        wrapped += 1
        shim_name = "imgui_kmp_" + (name[len("imgui_"):] if name.startswith("imgui_") else name)
        args, call_args = [], []
        for i, (t, n) in enumerate(parsed):
            if t in structs:
                args.extend(f"float {n}_{field}" for field in structs[t])
                call_args.append(f"__s{i}")
            else:
                ctype = "uint32_t" if t == "uint64_t" else t
                args.append(f"{ctype} {n}")
                call_args.append(n)

        ret_ctype = "void" if (ret_struct or ret == "uint64_t") else ret
        out_params = []
        if ret_struct:
            out_params = [f"float* out_{f}" for f in structs[ret]]
        elif ret == "uint64_t":
            out_params = ["uint32_t* out_lo"]

        shim.append(f"{ret_ctype} {shim_name}({', '.join(args + out_params)}) {{")
        for i, (t, n) in enumerate(parsed):
            if t in structs:
                fields = structs[t]
                inits = ", ".join(f"{n}_{f}" for f in fields)
                shim.append(f"    {t} __s{i} = {{ {inits} }};")
        call = f"{name}({', '.join(call_args)})"
        if ret_struct:
            fields = structs[ret]
            shim.append(f"    {ret} r = {call};")
            for f in fields:
                shim.append(f"    *out_{f} = r.{f};")
        elif ret == "uint64_t":
            shim.append(f"    *out_lo = (uint32_t){call};")
        elif ret == "void":
            shim.append(f"    {call};")
        else:
            shim.append(f"    return {call};")
        shim.append("}")
        shim.append("")
        exports.append(shim_name)

    shim.append("} /* extern \"C\" */")
    (out_dir / "imgui_kmp_shim.cpp").write_text("\n".join(shim))

    js = [
        "/* Generated by imgui-kmp/wasm/gen_wasm_shim.py - do not edit. */",
        "export const IMGUI_KMP_EXPORTS = [",
    ]
    js += [f'  "{e}",' for e in exports]
    js.append("];")
    js.append("")
    (out_dir / "imgui_kmp_exports.js").write_text("\n".join(js))

    print(f"functions: {len(functions)}  wrapped: {wrapped}  exports: {len(exports)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
